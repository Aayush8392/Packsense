"""The real columns of the 20 portable gold models, read from the DuckDB fixture build (the same build the engines job compares).

  python p5_governance/bootstrap/gold_columns.py dump  --duckdb p4_modelling/target/fixture.duckdb    # rewrite p5_governance/gold_columns.json
  python p5_governance/bootstrap/gold_columns.py check --duckdb p4_modelling/target/fixture.duckdb    # exit 1 if the committed file differs

Needs the `duckdb` package (the dbt environment has it). `check` runs in the `engines` CI job, so a model that gains or loses a column
cannot leave the data classification stale without a red job there. Only table and column names are read.
"""
import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
P5 = HERE.parent
sys.path.insert(0, str(P5.parent / "p4_modelling"))
OUT = P5 / "gold_columns.json"


def read(db: str) -> dict[str, list[str]]:
    import duckdb
    from gold_lib.compare import MODELS

    con = duckdb.connect(db, read_only=True)
    models = {}
    for m in sorted(MODELS):
        cols = [r[0] for r in con.execute(
            "select column_name from information_schema.columns where table_name = ? order by ordinal_position", [m]).fetchall()]
        if not cols:
            raise SystemExit(f"model {m} is not in {db}: build the fixture first (dbt build --target duckdb)")
        models[m] = cols
    return models


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", choices=["dump", "check"])
    ap.add_argument("--duckdb", required=True)
    args = ap.parse_args(argv)
    models = read(args.duckdb)
    text = json.dumps({"note": "generated by bootstrap/gold_columns.py from the DuckDB fixture build; do not edit by hand", "models": models},
                      indent=1) + "\n"
    if args.mode == "dump":
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUT.name}: {len(models)} models, {sum(len(c) for c in models.values())} columns")
        return 0
    have = json.loads(OUT.read_text(encoding="utf-8"))["models"]
    if have == models:
        print(f"gold_columns.json equals the build: {len(models)} models, {sum(len(c) for c in models.values())} columns")
        return 0
    for m in sorted(set(have) | set(models)):
        if have.get(m) != models.get(m):
            print(f"DIFFERENT {m}: committed {have.get(m)} vs build {models.get(m)}")
    print("regenerate with: python p5_governance/bootstrap/gold_columns.py dump --duckdb <db>, then render_classification.py")
    return 1


if __name__ == "__main__":
    sys.exit(main())
